/**
 * tools/bundle.mjs
 *
 * Emits dist/a11y-bundle.js: one file to paste into a code injection box.
 *
 * A code injection box takes a blob of script, not a module graph, so the
 * shipped artefact has to be a single concatenation in dependency order. The
 * alternative is telling a client to paste eleven script tags in the right
 * sequence, which they will get wrong once and then never touch again.
 *
 *   node tools/bundle.mjs            write the bundle
 *   node tools/bundle.mjs --check    fail if the bundle is out of date
 *
 * CI runs the second form, so the bundle cannot drift from its sources. That
 * matters more than it sounds: the bundle is the only file most users of
 * this repository will ever read, and a stale one would ship the exact
 * defects this deepening was written to remove.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist', 'a11y-bundle.js');

/* Order matters and is the same order test/harness.mjs loads: the string
   helpers before the name computation that uses them, both before the
   engine, the engine before the rules that register on it. */
export function sources() {
  const rules = readdirSync(path.join(ROOT, 'rules'))
    .filter((f) => f.endsWith('.js'))
    .sort()
    .map((f) => path.posix.join('rules', f));
  return ['lib/text.js', 'lib/accessible-name.js', 'shared/a11y-injection-kit.js', ...rules];
}

const HEADER = [
  '/* a11y-injection-kit bundle',
  ' *',
  ' * Generated by tools/bundle.mjs. Do not edit this file: edit the sources',
  ' * listed below and run `npm run bundle`. CI fails if the two disagree.',
  ' *',
  ' * Paste into the platform code injection box, footer or body end, and read',
  ' * the README first. Everything the platform editor can set should be set in',
  ' * the editor. What is left is what this is for.',
  ' *'
];

export function build() {
  const files = sources();
  const parts = [
    ...HEADER,
    ...files.map((f) => ' *   ' + f),
    ' */',
    ''
  ];
  for (const file of files) {
    parts.push('/* ===== ' + file + ' ===== */');
    parts.push(readFileSync(path.join(ROOT, file), 'utf8').trimEnd());
    parts.push('');
  }
  parts.push('/* ===== start ===== */');
  parts.push('window.A11yKit.start();');
  parts.push('');
  return parts.join('\n');
}

/* Only act when run directly. tools/verify.mjs imports sources() from here,
   and an import that writes a file as a side effect is how a verifier ends up
   certifying output it generated itself one millisecond earlier. */
const RUN_DIRECTLY = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (!RUN_DIRECTLY) {
  // nothing to do on import
} else if (process.argv.includes('--check')) {
  if (!existsSync(OUT)) {
    console.error('dist/a11y-bundle.js does not exist. Run: npm run bundle');
    process.exit(1);
  }
  const onDisk = readFileSync(OUT, 'utf8');
  if (onDisk !== build()) {
    console.error('dist/a11y-bundle.js is out of date. Run: npm run bundle');
    process.exit(1);
  }
  console.log('dist/a11y-bundle.js is up to date (' + sources().length + ' sources).');
} else {
  writeFileSync(OUT, build());
  console.log('Wrote dist/a11y-bundle.js from ' + sources().length + ' sources.');
}
